// Function to get a specific dot art pattern
function getDotArt(patternName) {
  return dotArtCollection[patternName] || null;
}

// Function to get all available dot art patterns
function getAllDotArt() {
  return Object.keys(dotArtCollection);
}

// Function to display dot art in console (for testing)
function displayDotArt(patternName) {
  const pattern = getDotArt(patternName);
  if (pattern) {
    console.log(pattern);
  } else {
    console.log(
      `Pattern "${patternName}" not found. Available patterns:`,
      getAllDotArt()
    );
  }
}

